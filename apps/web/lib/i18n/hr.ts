export type HrKey = keyof (typeof hrDict)["ca"];

/** Looks up `prefix + value` (e.g. "sig_" + "emergent"); returns `value` itself when there is no such key. */
export function hrLookup(prefix: string, value: string, lang: Lang): string {
  const key = `${prefix}${value}`;
  return key in hrDict.ca ? makeT(hrDict, lang)(key as HrKey) : value;
}
